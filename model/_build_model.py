"""Rebuild model/piper_umi.urdf (maintainers only; the package never runs this).

model/piper_umi_models/ is the complete Piper + UMI model package (URDF, MuJoCo XML, USD), copied unchanged; its
SHA256SUMS lists every file. model/piper_umi.urdf is that URDF with the console's IK numbers:
  joints 1-6   origins and axes from the piper-IK URDF the data_viewer console solves with (matches the controller's
               own FK to 0.1 mm); limits = Piper datasheet ∩ piper_sdk joint table (what the arm really reaches)
  tool0        UMI fingertip TCP, fixed on link6: model/tcp.json (the console's matrix) written as xyz / rpy
  links        inertias, visual and collision meshes and the prismatic finger joints (+ mimic) unchanged; the
               meshes are referenced inside piper_umi_models/urdf/meshes/

    python model/_build_model.py --piper-ik-urdf /path/to/piper-IK/piper_ik/assets/piper.urdf [--models /path/to/piper_umi_models]
--models first copies that model package into model/piper_umi_models (and checks it against its SHA256SUMS).
"""
import argparse
import hashlib
import json
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path
import numpy as np

HERE = Path(__file__).resolve().parent
MODELS = HERE / 'piper_umi_models'
TCP_FROM_FLANGE = np.array(json.loads((HERE / 'tcp.json').read_text())['matrix'], float)   # the console's matrix, kept as is
SPEC_DEG = ([-154., 0., -175., -100., -75., -170.], [154., 195., 0., 112., 75., 170.])
SDK_TABLE_DEG = ([-150., 0., -170., -100., -70., -120.], [150., 179.9, 0., 100., 70., 120.])


def rpy_to_matrix(r, p, y):
    cr, sr, cp, sp, cy, sy = np.cos(r), np.sin(r), np.cos(p), np.sin(p), np.cos(y), np.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr], [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr], [-sp, cp * sr, cp * cr]])


def matrix_to_rpy(R):
    return float(np.arctan2(R[2, 1], R[2, 2])), float(-np.arcsin(R[2, 0])), float(np.arctan2(R[1, 0], R[0, 0]))


def check_sums(root):
    """Every file listed in root/SHA256SUMS exists with that hash; returns the number of files."""
    n = 0
    for line in (root / 'SHA256SUMS').read_text().splitlines():
        digest, name = line.split(maxsplit=1); name = name.lstrip('*')
        if hashlib.sha256((root / name).read_bytes()).hexdigest() != digest:
            raise ValueError(f'{name}: checksum mismatch')
        n += 1
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--piper-ik-urdf', required=True, help="piper-IK piper_ik/assets/piper.urdf (the console's IK model)")
    ap.add_argument('--models', help='piper_umi_models folder to (re)copy into model/piper_umi_models')
    a = ap.parse_args()
    if a.models:
        if MODELS.exists():
            shutil.rmtree(MODELS)
        shutil.copytree(a.models, MODELS, ignore=shutil.ignore_patterns('.git', '__pycache__'))
    print('model package:', check_sums(MODELS), 'files match SHA256SUMS')
    robot = ET.parse(MODELS / 'urdf/piper_umi.urdf').getroot(); ik = ET.parse(a.piper_ik_urdf).getroot()
    for m in robot.findall('mujoco'):
        robot.remove(m)
    lo = np.maximum(np.deg2rad(SPEC_DEG[0]), np.deg2rad(SDK_TABLE_DEG[0])); hi = np.minimum(np.deg2rad(SPEC_DEG[1]), np.deg2rad(SDK_TABLE_DEG[1]))
    for i in range(6):
        name = f'joint{i + 1}'; src = ik.find(f"joint[@name='{name}']"); dst = robot.find(f"joint[@name='{name}']")
        for tag in ('origin', 'axis'):
            dst.find(tag).attrib.update(src.find(tag).attrib)
        dst.find('limit').set('lower', repr(float(lo[i]))); dst.find('limit').set('upper', repr(float(hi[i])))
    for j in robot.findall('joint'):                                      # the CAD tool0 (on gripper_base) is replaced
        if j.find('child').get('link') == 'tool0':
            robot.remove(j)
    rpy = matrix_to_rpy(TCP_FROM_FLANGE[:3, :3]); assert np.abs(rpy_to_matrix(*rpy) - TCP_FROM_FLANGE[:3, :3]).max() < 1e-15
    tj = ET.SubElement(robot, 'joint', name='tool0_joint', type='fixed')
    ET.SubElement(tj, 'origin', xyz=' '.join(repr(float(v)) for v in TCP_FROM_FLANGE[:3, 3]), rpy=' '.join(repr(v) for v in rpy))
    ET.SubElement(tj, 'parent', link='link6'); ET.SubElement(tj, 'child', link='tool0')
    n = 0
    for mesh in robot.iter('mesh'):                                       # meshes stay where the model package keeps them
        path = 'piper_umi_models/urdf/' + mesh.get('filename'); assert (HERE / path).is_file(), path
        mesh.set('filename', path); n += 1
    ET.indent(robot, '  ')
    head = ('<?xml version="1.0"?>\n<!-- Piper + UMI gripper, one model for IK and planning. Generated by model/_build_model.py from\n'
            '     piper_umi_models/urdf/piper_umi.urdf: joints 1-6 = piper-IK kinematics (as the data_viewer console solves),\n'
            '     limits = datasheet ∩ piper_sdk table, tool0 = model/tcp.json (UMI fingertip TCP). Links, meshes and fingers\n'
            '     unchanged. Do not edit by hand. -->\n')
    (HERE / 'piper_umi.urdf').write_text(head + ET.tostring(robot, encoding='unicode') + '\n', encoding='utf-8')
    print('wrote', HERE / 'piper_umi.urdf', n, 'mesh references')


if __name__ == '__main__':
    main()
